#!/usr/bin/env python3
"""
Generate a LaTeX table of compression overhead percentages (mean ± stddev)
across 29 non-overlapping 32 MB regions of a large file.

Usage:
    python table_regions.py <input_json> [--output <output.tex>]

If --output is omitted, prints to stdout.
"""

import argparse
import json
import math
import sys


def mean(values):
    return sum(values) / len(values)


def stdev(values):
    if len(values) < 2:
        return 0.0
    m = mean(values)
    variance = sum((v - m) ** 2 for v in values) / (len(values) - 1)
    return math.sqrt(variance)


def fmt(s: float) -> str:
            return f"{s:.2f}".replace(".", ",")


def main():
    parser = argparse.ArgumentParser(
        description="Generate LaTeX table of compression overhead from region runs"
    )
    parser.add_argument("input_json", help="JSON file from run_regions.py")
    parser.add_argument("--output", "-o", help="Output .tex file (default: stdout)")
    parser.add_argument(
        "--debug",
        action="store_true",
        help="Print per-region raw values for debugging",
    )
    args = parser.parse_args()

    with open(args.input_json, "r") as f:
        data = json.load(f)

    compressor = data["compressor"]
    level = data["level"]
    num_regions = data["num_regions"]
    region_size_mb = data["region_size"] // (1024 * 1024)

    # Collect results per block size across all regions
    # block_size -> list of (blocked_overhead_pct, archive_overhead_pct)
    block_map = {}
    for region_idx_str, region_data in data["regions"].items():
        original_size = region_data["size"]
        original_mb = original_size / (1024 * 1024)
        for r in region_data["results"]:
            bs = r["block_size"]
            whole = r["whole"]
            blocked = r["blocked"]
            archive = r["archive"]

            blocked_overhead_pct = ((blocked - whole) / original_size) * 100
            archive_overhead_pct = ((archive - blocked) / original_size) * 100

            if bs not in block_map:
                block_map[bs] = {"blocked": [], "archive": []}
            block_map[bs]["blocked"].append(blocked_overhead_pct)
            block_map[bs]["archive"].append(archive_overhead_pct)

    block_sizes = sorted(block_map.keys())

    # Debug: print per-region raw values
    if args.debug:
        print("=== DEBUG: Per-region raw values ===", file=sys.stderr)
        for bs in block_sizes:
            print(f"\nBlock size {bs}:", file=sys.stderr)
            print(
                f"  {'Region':>6} | {'whole':>10} | {'blocked':>10} | {'archive':>10} | "
                f"{'blocked_over%':>13} | {'archive_over%':>14}",
                file=sys.stderr,
            )
            print(f"  {'-'*6}-+-{'-'*10}-+-{'-'*10}-+-{'-'*10}-+-{'-'*13}-+-{'-'*14}", file=sys.stderr)
            for region_idx_str, region_data in data["regions"].items():
                for r in region_data["results"]:
                    if r["block_size"] != bs:
                        continue
                    whole = r["whole"]
                    blocked = r["blocked"]
                    archive = r["archive"]
                    orig = region_data["size"]
                    b_pct = ((blocked - whole) / orig) * 100
                    a_pct = ((archive - blocked) / orig) * 100
                    print(
                        f"  {region_idx_str:>6} | {whole:>10} | {blocked:>10} | {archive:>10} | "
                        f"{b_pct:>12.4f}% | {a_pct:>13.4f}%",
                        file=sys.stderr,
                    )
        print(file=sys.stderr)

    # Build LaTeX table
    lines = []
    lines.append("% Auto-generated by table_regions.py")
    lines.append(f"% Compressor: {compressor}, level: {level}")
    lines.append(f"% {num_regions} regions x {region_size_mb} MB")
    lines.append(r"\begin{tabular}{lcc}")
    lines.append(r"\toprule")
    lines.append(
        r"  \multirow{2}{*}{\shortstack[l]{Размер блока\\[3pt](байт)}} "
        r"& \multicolumn{2}{c}{Накладные расходы (\% от оригинала)} \\"
    )
    lines.append(r"  \cmidrule(lr){2-3}")
    lines.append(
        r"  & \textbf{Блочное сжатие} & \textbf{Метаданные Compio} \\"
    )
    lines.append(r"  \midrule")

    for bs in block_sizes:
        blocked_vals = block_map[bs]["blocked"]
        archive_vals = block_map[bs]["archive"]

        blocked_mean_val = fmt(mean(blocked_vals))
        blocked_std_val = fmt(stdev(blocked_vals))
        archive_mean_val = fmt(mean(archive_vals))
        archive_std_val = fmt(stdev(archive_vals))

        # Determine which is lower (better) for bold formatting
        # Bold the better (lower overhead) value
        blocked_str = (
            f"\\textbf{{{blocked_mean_val}}}{{\\small$\\,\\pm\\,{blocked_std_val}$}}"
        )
        archive_str = (
            f"\\textbf{{{archive_mean_val}}}{{\\small$\\,\\pm\\,{archive_std_val}$}}"
        )

        lines.append(
            f"    {bs} & {blocked_str} & {archive_str} \\\\"
        )

    lines.append(r"  \bottomrule")
    lines.append(r"\end{tabular}")

    output = "\n".join(lines) + "\n"

    if args.output:
        with open(args.output, "w") as f:
            f.write(output)
        print(f"Table saved to {args.output}")
    else:
        print(output)


if __name__ == "__main__":
    main()
